create table if not exists public.cancellation_cases (
    case_id bigint generated by default as identity primary key,
    customer_id text not null,
    request_date date not null,
    plan text,
    contract_type text,
    tenure double precision,
    monthly_charge double precision,
    primary_reason text not null,
    secondary_reason text,
    customer_comments text,
    stay_request text,
    retention_action text not null,
    outcome text not null,
    cancellation_status text not null default 'Not cancelled',
    cancellation_date date,
    owner text,
    follow_up_date date,
    notes text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint cancellation_status_date_check
        check (cancellation_status <> 'Cancelled' or cancellation_date is not null)
);

create index if not exists idx_cancellation_cases_request_date
    on public.cancellation_cases (request_date desc);
create index if not exists idx_cancellation_cases_customer_date
    on public.cancellation_cases (customer_id, request_date);

alter table public.cancellation_cases enable row level security;
revoke all on table public.cancellation_cases from anon, authenticated;
grant all on table public.cancellation_cases to service_role;
grant usage, select on sequence public.cancellation_cases_case_id_seq to service_role;

